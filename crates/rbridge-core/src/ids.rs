use std::fmt;

use serde::{Deserialize, Serialize};

use crate::chain::Chain;
use crate::error::BridgeError;
use crate::keccak256_hex;

/// A native-chain deposit, identified by the chain, vault, transaction hash and log
/// index. The id is one-shot on rholo: a second mint with the same id is a no-op.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
pub struct DepositId(String);

impl DepositId {
    pub fn new(hex: impl Into<String>) -> Result<Self, BridgeError> {
        let hex = hex.into();
        if hex.len() != 64 || !hex.chars().all(|c| c.is_ascii_hexdigit()) {
            return Err(BridgeError::BadHex(hex));
        }
        Ok(Self(hex.to_ascii_lowercase()))
    }

    pub fn from_parts(
        chain: Chain,
        vault: &str,
        tx_hash: &str,
        log_index: u32,
    ) -> Result<Self, BridgeError> {
        for (field, value) in [("vault", vault), ("tx_hash", tx_hash)] {
            if value.is_empty() || value.contains('|') || value.len() > 256 {
                return Err(BridgeError::InvalidField {
                    field,
                    reason: "must be non-empty, <=256 bytes and contain no '|'",
                });
            }
        }
        let canonical = format!(
            "rbridge:deposit:v1|{}|{}|{}|{}",
            chain.as_str(),
            vault,
            tx_hash,
            log_index
        );
        Self::new(keccak256_hex(canonical.as_bytes()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for DepositId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// A rholo burn that a relayer will unlock on the native chain. The op id is the burn
/// deploy's idempotency key; it is generated by the client and consumed by `Bridge.burn`.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
pub struct WithdrawalId(String);

impl WithdrawalId {
    pub fn new(value: impl Into<String>) -> Result<Self, BridgeError> {
        let value = value.into();
        let valid = !value.is_empty()
            && value.len() <= 128
            && !value.contains('|')
            && value
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | ':' | '.'));
        if valid {
            Ok(Self(value))
        } else {
            Err(BridgeError::InvalidField {
                field: "withdrawal_id",
                reason: "must be 1..=128 ASCII alphanumerics or - _ : .",
            })
        }
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for WithdrawalId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn deposit_ids_are_deterministic_and_index_sensitive() {
        let a = DepositId::from_parts(Chain::Ethereum, "0xvault", "0xtx", 0).expect("id");
        let b = DepositId::from_parts(Chain::Ethereum, "0xvault", "0xtx", 0).expect("id");
        let c = DepositId::from_parts(Chain::Ethereum, "0xvault", "0xtx", 1).expect("id");
        assert_eq!(a, b);
        assert_ne!(a, c);
        assert_eq!(a.as_str().len(), 64);
    }

    #[test]
    fn malformed_deposit_ids_are_refused() {
        assert!(DepositId::new("abc").is_err());
        assert!(DepositId::new("z".repeat(64)).is_err());
        assert!(DepositId::from_parts(Chain::Tron, "a|b", "0xtx", 0).is_err());
    }

    #[test]
    fn withdrawal_ids_refuse_delimiters() {
        assert!(WithdrawalId::new("burn-1").is_ok());
        assert!(WithdrawalId::new("burn|1").is_err());
        assert!(WithdrawalId::new("").is_err());
    }
}
